import { Inject, Injectable } from '@nestjs/common';
import { camelizeKeys } from '../common/format';
import type { Database } from '../supabase/database.types';
import type { Db } from '../supabase/supabase.module';
import { SUPABASE_CLIENT } from '../supabase/supabase.module';
import { unwrap } from '../supabase/supabase-result';
import { AnnualExportsDto, MonthlyDataDto } from './admin.dto';
import { vpdKpa } from './vpd';

type MonthlyDataInsert = Database['public']['Tables']['monthly_data']['Insert'];

@Injectable()
export class AdminDataService {
  constructor(@Inject(SUPABASE_CLIENT) private readonly db: Db) {}

  /**
   * Insert or update one month. Only the columns below are written, so an
   * existing row keeps its `price_valid` flag; `farmgate_regional_avg` is
   * generated by the database. Returns the stored row in camelCase.
   */
  async upsertMonthlyData(
    dto: MonthlyDataDto,
  ): Promise<Record<string, unknown>> {
    const row: MonthlyDataInsert = {
      month: dto.month,
      farmgate_davao_city: dto.farmgateDavaoCity,
      farmgate_davao_de_oro: dto.farmgateDavaoDeOro,
      farmgate_davao_del_norte: dto.farmgateDavaoDelNorte,
      farmgate_davao_del_sur: dto.farmgateDavaoDelSur,
      farmgate_davao_occidental: dto.farmgateDavaoOccidental,
      farmgate_davao_oriental: dto.farmgateDavaoOriental,
      cpi_region11: dto.cpiRegion11,
      temp_c: dto.tempC,
      rh_pct: dto.rhPct,
      rain_mm: dto.rainMm,
      vpd_kpa: vpdKpa(dto.tempC, dto.rhPct),
      coconut_oil_usd_mt: dto.coconutOilUsdMt,
      palm_oil_usd_mt: dto.palmOilUsdMt,
      palm_kernel_oil_usd_mt: dto.palmKernelOilUsdMt,
      soybean_oil_usd_mt: dto.soybeanOilUsdMt,
      php_usd: dto.phpUsd,
      source_note: dto.sourceNote ?? null,
    };
    const stored = unwrap(
      await this.db
        .from('monthly_data')
        .upsert(row, { onConflict: 'month' })
        .select('*')
        .single(),
      `upsert monthly_data ${dto.month}`,
    );
    return camelizeKeys(stored);
  }

  /** Insert or update one year of the export unit value. */
  async upsertAnnualExports(
    dto: AnnualExportsDto,
  ): Promise<Record<string, unknown>> {
    const stored = unwrap(
      await this.db
        .from('annual_exports')
        .upsert(
          {
            year: dto.year,
            unit_value_usd_kg: dto.unitValueUsdKg,
            source_note: dto.sourceNote ?? null,
          },
          { onConflict: 'year' },
        )
        .select('*')
        .single(),
      `upsert annual_exports ${dto.year}`,
    );
    return camelizeKeys(stored);
  }
}
